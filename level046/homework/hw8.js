// map()

// map() გადაუვლის მასივის ყველა ელემენტს,
// თითოეულ ელემენტზე შეასრულებს callback ფუნქციას
// და დააბრუნებს ახალ მასივს შეცვლილი მნიშვნელობებით.
//
// მთავარი თვისება:
// აბრუნებს ახალ მასივს
// ახალი მასივის სიგრძე იგივეა რაც თავდაპირველის

const numbers = [1, 2, 3];

const doubled = numbers.map(num => num * 2);

console.log(doubled); // [2, 4, 6]



// reduce()

// reduce() მასივის ყველა ელემენტს
// ერთ საბოლოო მნიშვნელობამდე ამცირებს.
//
// ხშირად გამოიყენება:
// ჯამის გამოსათვლელად
// ნამრავლის საპოვნელად
// მაქსიმუმის/მინიმუმის საპოვნელად
//
// accumulator - ინახავს შუალედურ შედეგს
// currentValue - მიმდინარე ელემენტია

const nums = [10, 20, 30];

const sum = nums.reduce((accumulator, currentValue) => {
    return accumulator + currentValue;
}, 0);

console.log(sum); // 60



// =========================
// filter()
// =========================

// filter() ქმნის ახალ მასივს,
// რომელშიც ხვდება მხოლოდ ის ელემენტები,
// რომლებიც აკმაყოფილებენ მოცემულ პირობას.
//
// მთავარი თვისება:
// - აბრუნებს ახალ მასივს
// - შეიძლება ახალი მასივი უფრო პატარა იყოს

const ages = [12, 18, 25, 15, 30];

const adults = ages.filter(age => age >= 18);

console.log(adults); // [18, 25, 30]



// =========================
// forEach()
// =========================

// forEach() გადაუვლის მასივის ყველა ელემენტს
// და თითოეულზე შეასრულებს callback ფუნქციას.
//
// მთავარი თვისება:
// - არაფერს არ აბრუნებს (undefined)
// - გამოიყენება მაშინ, როცა მხოლოდ მოქმედების
//   შესრულება გვინდა (მაგ: console.log)

const names = ["Nino", "Gio", "Luka"];

names.forEach(name => {
    console.log(name);
});

// Nino
// Gio
// Luka