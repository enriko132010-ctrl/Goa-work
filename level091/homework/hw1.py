# აჩვენებს მიმდინარე ფოლდერში არსებულ ფაილებს და საქაღალდეებს

# ls


# pwd (print working directory)
# აჩვენებს რომელ დირექტორიაში ვიმყოფებით

# pwd

# cd (change directory)
# გადადის სხვა დირექტორიაში

# cd Documents
# გადაგვიყვანს Documents საქაღალდეში


# mkdir (make directory)
# ქმნის ახალ საქაღალდეს

# mkdir ReactProject
# შეიქმნა ReactProject ფოლდერი

# touch
# ქმნის ახალ ფაილს

# touch app.js
# შეიქმნა app.js ფაილი


# rm (remove)
# შლის ფაილს

# rm app.js
# წაიშლება app.js


# rmdir (remove directory)
# შლის საქაღალდეს

# rmdir ReactProject
# წაიშალა ReactProject ფოლდერი



# cp (copy)
# აკოპირებს ფაილს ერთი ადგილიდან მეორეში

# cp app.js backup.js
# app.js-ის ასლი შეიქმნა backup.js სახელით

# cp -r
# აკოპირებს მთლიან საქაღალდეს მის შიგთავსთან ერთად

# cp -r Project ProjectCopy
# Project საქაღალდე დაკოპირდა ProjectCopy-ში