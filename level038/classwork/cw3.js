const num1 = 5;
const num2 = 3;

console.log(num1 + num2); // მიმატება
console.log(num1 - num2); // გამოკლება
console.log(num1 * num2); // გამრავლება
console.log(num1 / num2); // გაყოფა
console.log(num1 == num2); // არა მკაცრი ტოლობა ანუ ტიპს არ ამოწმებს
console.log(num1 === num2); // მკაცრი ტოლობა ანუ ტიპსაც ამოწმებს
console.log(num1 != num2); // არა მკაცრი შემოწმება
console.log(num1 !== num2); // მკაცრი